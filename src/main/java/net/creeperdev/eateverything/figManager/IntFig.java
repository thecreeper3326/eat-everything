package net.creeperdev.sleepDeprivation.figManager;

public class IntFig {
        public String name;
        public String description;
        public int value;
        public int min;
        public int max;
        public IntFig(String name, String description, int value, int min, int max) {
            this.name = name;
            this.description = description;
            this.value = value;
            this.min = min;
            this.max = max;
        }
    }