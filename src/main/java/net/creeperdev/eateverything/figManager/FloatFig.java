package net.creeperdev.sleepDeprivation.figManager;

public class FloatFig {
        public String name;
        public String description;
        public float value;
        public float min;
        public float max;
        public FloatFig(String name, String description, float value, float min, float max) {
            this.name = name;
            this.description = description;
            this.value = value;
            this.min = min;
            this.max = max;
        }
    }